package lalrgen.viz;

import lalrgen.core.CompiledSpec;
import lalrgen.grammar.Grammar;
import lalrgen.grammar.Production;
import lalrgen.spec.PrecDecl;
import lalrgen.spec.SymRef;

import java.util.HashMap;
import java.util.Map;

/**
 * Converts a spec's grammar into a Bison .y file (no actions), so Bison can be used as an
 * independent oracle: its LALR state count and conflict counts should match ours.
 * Every literal becomes a named token LIT_n so no character escaping is needed.
 */
public final class BisonExporter {
    private BisonExporter() {}

    public static String export(CompiledSpec cs) {
        Grammar g = cs.grammar();
        Map<String, String> bisonName = new HashMap<>();
        int lit = 0;
        StringBuilder sb = new StringBuilder("/* Generated by lalrgen from ").append(cs.spec().fileName()).append(" */\n");
        for (int t = 1; t < g.terminalCount(); t++) {
            String n = g.name(t);
            String b = n.startsWith("'") ? "LIT_" + (++lit) : safe(n);
            bisonName.put(n, b);
            sb.append("%token ").append(b);
            if (n.startsWith("'")) sb.append("   /* ").append(n.replace("*/", "* /")).append(" */");
            sb.append('\n');
        }
        for (PrecDecl d : cs.spec().precs()) {
            sb.append(switch (d.assoc()) {
                case LEFT -> "%left";
                case RIGHT -> "%right";
                case NONASSOC -> "%nonassoc";
            });
            for (SymRef s : d.names()) sb.append(' ').append(bisonName.getOrDefault(s.name(), safe(s.name())));
            sb.append('\n');
        }
        sb.append("%start ").append(safe(g.name(g.start()))).append("\n%%\n");
        for (int a = g.terminalCount() + 1; a < g.symbolCount(); a++) {
            sb.append(safe(g.name(a))).append('\n');
            boolean first = true;
            for (Production p : g.productionsOf(a)) {
                sb.append(first ? "  :" : "  |");
                first = false;
                if (p.length() == 0) sb.append(" %empty");
                for (int s : p.rhs()) sb.append(' ').append(g.isTerminal(s) ? bisonName.get(g.name(s)) : safe(g.name(s)));
                String prec = precName(cs, p);
                if (prec != null) sb.append(" %prec ").append(bisonName.getOrDefault(prec, safe(prec)));
                sb.append('\n');
            }
            sb.append("  ;\n");
        }
        return sb.append("%%\n").toString();
    }

    private static String precName(CompiledSpec cs, Production p) {
        // find the matching alternative's %prec, if any, by position
        for (var r : cs.spec().rules()) {
            for (var alt : r.alts()) {
                if (alt.pos().equals(p.pos()) && alt.prec() != null) return alt.prec().name();
            }
        }
        return null;
    }

    private static String safe(String n) {
        return n.equals("error") ? "error_" : n;
    }
}
